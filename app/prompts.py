def build_profile_prompt(qa_pairs):
    qa_text = "\n".join(
        f"Q{i+1}. {q}\nA: {a}" for i, (q, a) in enumerate(qa_pairs)
    )
    return (
        "以下是用户的诊断问卷回答,请生成他的认知与内核训练画像。\n"
        "严格只输出如下 JSON(不要多余文字、不要代码块标记):\n"
        "{\n"
        '  "decision_style": "谨慎型/冲动型/犹豫摇摆型 之一,并简要说明",\n'
        '  "emotion_trigger": "情绪敏感源描述",\n'
        '  "recovery_speed": "抗压恢复速度描述",\n'
        '  "bias_tendency": "典型认知偏差倾向,逗号分隔",\n'
        '  "summary_text": "一段完整的画像描述",\n'
        '  "attention": 0-100 注意力评分(当前相对基线,真实反映强弱不讨好),\n'
        '  "memory": 0-100 记忆力评分,\n'
        '  "reasoning": 0-100 逻辑评分,\n'
        '  "executive": 0-100 执行功能评分,\n'
        '  "metacog": 0-100 元认知评分,\n'
        '  "regulation": 0-100 情绪调节评分\n'
        "}\n\n"
        f"问卷回答:\n{qa_text}"
    )


def build_scenario_prompt(profile_text):
    return (
        "根据用户诊断画像,出一道今天可用的场景推演题。"
        "要贴合他的具体决策风格/情绪敏感源/认知偏差,不是通用题。"
        "只用一道题,像教练抛给他一个真实会遇到的情境,"
        "引导他做出判断或选择。控制在 80 字以内。\n\n"
        f"用户画像:\n{profile_text}"
    )


def build_followup_prompt(entry_text, profile_text):
    return (
        "用户刚提交了一条记录。先不要给结论,只针对他刚才记录里的某一句话或某个判断,"
        "提一个具体的追问(只问一个问题)。参考他的诊断画像,让追问贴合他。\n\n"
        f"用户画像:\n{profile_text}\n\n用户记录:\n{entry_text}"
    )


def build_weekly_prompt(entries_text, streak):
    return (
        "以下是用户本周的全部训练记录,请生成一份结构化周报。\n"
        "包含:本周总体观察(决策质量/认知偏差/情绪韧性方面的趋势)、"
        "最值得注意的 1-2 个模式、下周可刻意练习的一件事。\n"
        f"当前连续记录周数:{streak} 周。\n\n"
        f"本周记录:\n{entries_text}"
    )


def build_training_question_prompt(news_summary):
    return (
        "基于下面这条新闻摘要,生成一道让用户结合自己决策/判断来思考的追问。"
        "要能牵引到他自身的认知或行为,不要讨论新闻本身。只问一个问题,30 字以内。\n\n"
        f"新闻:{news_summary}"
    )


